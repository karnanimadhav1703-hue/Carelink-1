import { act, cleanup, render, screen } from '@testing-library/react';
import { afterEach, beforeEach, expect, it, vi } from 'vitest';
const mocks = vi.hoisted(() => ({ listeners: {}, record: vi.fn(), notify: vi.fn(), speak: vi.fn() }));
vi.mock('../lib/database', () => ({ watchPatientRecords: (name, uid, callback) => { mocks.listeners[name] = callback; return vi.fn(); } }));
vi.mock('../lib/medicineDatabase', () => ({ recordDose: mocks.record }));
vi.mock('../lib/notifications', () => ({ notifyDose: mocks.notify }));
vi.mock('./ModeContext', () => ({ useMode: () => ({ mode: 'vision-assist' }) }));
vi.mock('./SpeechContext', () => ({ useSpeech: () => ({ speak: mocks.speak }) }));
vi.mock('./AuthContext', () => ({ useAuth: () => ({ user: { uid: 'p1' }, profile: { role: 'patient', name: 'Meena' } }) }));
import { MedicineProvider } from './MedicineContext';
import DoseReminders from '../components/DoseReminders';
import { doseId, MISSED_AFTER_MS } from '../lib/doses';
const start = new Date(2026, 9, 23, 9).getTime();
const medicine = { id: 'm1', patientId: 'p1', name: 'Example', dose: '1 tablet', times: [], createdAt: start - 1000, demoAt: start + 60000 };
beforeEach(() => { vi.useFakeTimers(); vi.setSystemTime(start); vi.clearAllMocks(); sessionStorage.clear(); mocks.record.mockResolvedValue(true); mocks.notify.mockResolvedValue(); });
afterEach(() => { cleanup(); vi.useRealTimers(); });
it('waits for both listeners, reminds at one minute, speaks once and marks missed after 15 more minutes', async () => {
  render(<MedicineProvider><DoseReminders /></MedicineProvider>);
  act(() => mocks.listeners.medicines([medicine]));
  await act(async () => vi.advanceTimersByTime(60000));
  expect(screen.queryByText('A dose is due')).toBeNull();
  act(() => mocks.listeners.doseLogs([]));
  expect(screen.getByText('A dose is due')).toBeTruthy();
  expect(mocks.notify).toHaveBeenCalledTimes(1);
  expect(mocks.speak).toHaveBeenCalledTimes(1);
  await act(async () => vi.advanceTimersByTime(MISSED_AFTER_MS - 10000));
  expect(mocks.record).not.toHaveBeenCalled();
  await act(async () => vi.advanceTimersByTime(10000));
  expect(mocks.record).toHaveBeenCalledWith('p1', expect.objectContaining({ id: doseId('m1', medicine.demoAt) }), 'missed', 'Meena', [medicine]);
  expect(mocks.notify).toHaveBeenCalledTimes(1);
});
it('a confirmed Taken log clears the reminder and prevents a missed alert', async () => {
  render(<MedicineProvider><DoseReminders /></MedicineProvider>);
  act(() => { mocks.listeners.medicines([medicine]); mocks.listeners.doseLogs([]); });
  await act(async () => vi.advanceTimersByTime(60000));
  await act(async () => screen.getByRole('button', { name: /Taken:/ }).click());
  expect(mocks.record).toHaveBeenCalledWith('p1', expect.anything(), 'taken', 'Meena', [medicine]);
  act(() => mocks.listeners.doseLogs([{ id: doseId('m1', medicine.demoAt), status: 'taken' }]));
  expect(screen.queryByText('A dose is due')).toBeNull();
  await act(async () => vi.advanceTimersByTime(MISSED_AFTER_MS));
  expect(mocks.record).toHaveBeenCalledTimes(1);
});
it('keeps a failed missed save visible and retries after reconnecting', async () => {
  mocks.record.mockRejectedValueOnce(new Error('offline'));
  render(<MedicineProvider><DoseReminders /></MedicineProvider>);
  act(() => { mocks.listeners.medicines([medicine]); mocks.listeners.doseLogs([]); });
  await act(async () => vi.advanceTimersByTime(60000 + MISSED_AFTER_MS));
  expect(screen.getByText(/missed-dose alert could not be saved/)).toBeTruthy();
  await act(async () => vi.advanceTimersByTime(20000));
  expect(mocks.record).toHaveBeenCalledTimes(1);
  await act(async () => vi.advanceTimersByTime(10000));
  expect(mocks.record).toHaveBeenCalledTimes(2);
  expect(screen.queryByText(/missed-dose alert could not be saved/)).toBeNull();
});
